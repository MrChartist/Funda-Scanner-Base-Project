describe("determinism (§F.1, §F.3)", () => {
  afterEach(() => {
    vi.useRealTimers();
    vi.restoreAllMocks();
  });

  it("generates deep-equal output twice, whatever the clock says, without Math.random", () => {
    const random = vi.spyOn(Math, "random");
    vi.useFakeTimers();
    vi.setSystemTime("2031-01-15T10:00:00Z");
    const a = generateSampleDataset();
    vi.setSystemTime("1999-07-01T00:00:00Z");
    const b = generateSampleDataset({ seed: SAMPLE_SEED, count: SAMPLE_COUNT });
    expect(a).toEqual(b);
    expect(JSON.stringify(a)).toBe(JSON.stringify(DS));
    expect(random).not.toHaveBeenCalled();
  });

  it("gives every company its own stream: subsets and prefixes match the full sample", () => {
    const first10 = generateSampleDataset({ count: 10 });
    expect(first10.companies).toEqual(DS.companies.slice(0, 10));
    const subset = generateSampleSubset(["power-03", "it-01"]);
    expect(subset.companies[0]).toEqual(DS.companies[PLANS.findIndex((p) => p.slug === "power-03")]);
    expect(subset.companies[1]).toEqual(DS.companies[0]);
    expect(generateSampleDataset({ count: 0 }).companies).toEqual([]);
  });

  it("changes the figures, not the roster, with another seed", () => {
    const other = generateSampleDataset({ seed: 7 });
    expect(other.meta.generator?.seed).toBe(7);
    expect(other.companies.map((c) => c.symbol)).toEqual(DS.companies.map((c) => c.symbol));
    expect(other.companies[0].annual[0].revenue).not.toBe(DS.companies[0].annual[0].revenue);
  });

  it("rejects counts and seeds that are not whole numbers", () => {
    expect(() => generateSampleDataset({ count: -1 })).toThrow(/whole number/);
    expect(() => generateSampleDataset({ count: 2.5 })).toThrow(/whole number/);
    expect(() => generateSampleDataset({ seed: 1.5 })).toThrow(/whole number/);
    expect(() => generateSampleSubset(["nope-01"])).toThrow(/Unknown sample slug/);
  });

  it("uses only + − × ÷ and Math.round/floor/min/max/abs/sqrt, and never reads the clock", () => {
    const dir = "src/lib/sample";
    const sources = readdirSync(dir).filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts"));
    expect(sources.length).toBeGreaterThanOrEqual(11);
    for (const f of sources) {
      const code = readFileSync(`${dir}/${f}`, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
      const mathCalls = code.match(/Math\.[a-zA-Z0-9]+/g) ?? [];
      for (const m of mathCalls) expect(["Math.round", "Math.floor", "Math.min", "Math.max", "Math.abs", "Math.sqrt", "Math.imul"], `${f}: ${m}`).toContain(m);
      expect(code, f).not.toMatch(/\*\*/);
      expect(code, f).not.toMatch(/\bDate\b/);
      expect(code, f).not.toMatch(/performance\.now|crypto\./);
    }
  });
});

