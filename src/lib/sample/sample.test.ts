describe("archetype intent (local arithmetic on raw fields)", () => {
  const capitalEmployed = (r: AnnualRow) => netWorth(r) + n(r, "non_controlling_interest") + n(r, "borrowings_non_current")
    + n(r, "borrowings_current") + n(r, "lease_liabilities");
  const ebit = (r: AnnualRow) => n(r, "revenue") - n(r, "operating_expenses") + n(r, "other_income") - n(r, "depreciation");
  const roceAvg5 = (c: CompanyRecord) => {
    let total = 0;
    for (let year = 2022; year <= 2026; year++) {
      total += (ebit(fy(c, year)) / ((capitalEmployed(fy(c, year)) + capitalEmployed(fy(c, year - 1))) / 2)) * 100;
    }
    return total / 5;
  };
  const cagr = (c: CompanyRecord, field: keyof AnnualRow, years: number) => {
    const end = n(fy(c, 2026), field);
    const start = n(fy(c, 2026 - years), field);
    let lo = -1;
    let hi = 2;
    for (let k = 0; k < 60; k++) {
      const mid = (lo + hi) / 2;
      let g = 1;
      for (let j = 0; j < years; j++) g *= 1 + mid;
      if (start * g < end) lo = mid;
      else hi = mid;
    }
    return lo * 100;
  };
  const ttmEps = (c: CompanyRecord) => c.quarterly.slice(-4).reduce((s, q) => s + (q.net_profit_owners ?? 0), 0) / (c.market.shares_outstanding ?? NaN);

  it("compounders earn high returns and grow at double digits", () => {
    for (const c of byArchetype("compounder")) {
      expect(roceAvg5(c), c.symbol).toBeGreaterThan(15);
      expect(cagr(c, "revenue", 5), c.symbol).toBeGreaterThan(10);
      expect(cagr(c, "net_profit", 5), c.symbol).toBeGreaterThan(10);
    }
  });

  it("cash-rich companies never borrow, so their finance cost is exactly 0", () => {
    for (const c of byArchetype("cash_rich")) {
      for (const r of c.annual) {
        expect(r.finance_cost, `${c.symbol} FY${r.fiscal_year}`).toBe(0);
        expect(n(r, "borrowings_non_current") + n(r, "borrowings_current") + n(r, "lease_liabilities")).toBe(0);
      }
    }
  });

  it("leveraged utilities borrow more than their equity", () => {
    for (const c of byArchetype("leveraged_utility")) {
      const r = fy(c, 2026);
      expect((n(r, "borrowings_non_current") + n(r, "borrowings_current")) / netWorth(r), c.symbol).toBeGreaterThan(1);
    }
  });

  it("value traps shrink while trading at a low P/E", () => {
    for (const c of byArchetype("value_trap")) {
      expect(n(fy(c, 2026), "revenue"), c.symbol).toBeLessThan(n(fy(c, 2021), "revenue"));
      const pe = (c.market.price ?? NaN) / ttmEps(c);
      expect(pe, c.symbol).toBeGreaterThan(0);
      expect(pe, c.symbol).toBeLessThan(10);
    }
  });

  it("turnarounds move from recent losses back to profit", () => {
    for (const c of byArchetype("turnaround")) {
      // Loss years FY2020–FY2024, including the first year of the 3-year window the template reads.
      expect(c.annual.filter((r) => r.fiscal_year >= 2020 && r.fiscal_year <= 2024).every((r) => n(r, "net_profit") < 0), c.symbol).toBe(true);
      expect(n(fy(c, 2024), "net_profit"), c.symbol).toBeLessThan(0);
      expect(n(fy(c, 2026), "net_profit"), c.symbol).toBeGreaterThan(0);
      expect(c.quarterly.slice(-4).reduce((s, q) => s + (q.net_profit ?? Number.NaN), 0), c.symbol).toBeGreaterThan(0);
    }
  });

  it("expensive growers grow fast and carry a very high P/E", () => {
    for (const c of byArchetype("expensive_grower")) {
      const years = withTrait("new_listing").includes(c) ? 3 : 5;
      expect(cagr(c, "revenue", years), c.symbol).toBeGreaterThan(20);
      expect((c.market.price ?? NaN) / ttmEps(c), c.symbol).toBeGreaterThan(60);
    }
  });

  it("dividend payers pay out most of their profit", () => {
    for (const c of byArchetype("dividend_payer")) {
      const r = fy(c, 2026);
      const payout = (n(r, "dividend_per_share") * n(r, "shares_outstanding_ye")) / n(r, "net_profit_owners");
      expect(payout, c.symbol).toBeGreaterThan(0.6);
      expect(payout, c.symbol).toBeLessThan(1);
    }
  });

  it("receivable build-up: debtor days up more than 30% in 3 years on slow sales growth", () => {
    for (const c of byArchetype("rf_receivables")) {
      const dd = (r: AnnualRow) => (n(r, "trade_receivables") / n(r, "revenue")) * 365;
      expect(dd(fy(c, 2026)) / dd(fy(c, 2023)), c.symbol).toBeGreaterThan(1.3);
      expect(cagr(c, "revenue", 3), c.symbol).toBeLessThan(10);
    }
  });

  it("high pledge: above 25% of the promoter holding and rising over a year", () => {
    for (const c of byArchetype("rf_pledge")) {
      const s = c.shareholding;
      const last = s[s.length - 1].promoter_pledged_pct ?? 0;
      const yearAgo = s[s.length - 5].promoter_pledged_pct ?? 0;
      expect(last, c.symbol).toBeGreaterThan(25);
      expect(last - yearAgo, c.symbol).toBeGreaterThan(5);
    }
    const others = DS.companies.filter((c) => plan(c).entry.archetype !== "rf_pledge");
    for (const c of others) for (const s of c.shareholding) expect(s.promoter_pledged_pct ?? 0, c.symbol).toBeLessThanOrEqual(10);
  });

  it("weak cash conversion: 5-year CFO below 70% of 5-year profit", () => {
    for (const c of byArchetype("rf_cash")) {
      const last5 = c.annual.slice(-5);
      const ratio = last5.reduce((s, r) => s + n(r, "cfo"), 0) / last5.reduce((s, r) => s + n(r, "net_profit"), 0);
      expect(ratio, c.symbol).toBeLessThan(0.7);
    }
  });

  it("serial diluters grow their share count by more than 5% every year", () => {
    for (const c of byArchetype("serial_diluter")) {
      for (let year = 2017; year <= 2026; year++) {
        const growth = n(fy(c, year), "shares_outstanding_ye") / n(fy(c, year - 1), "shares_outstanding_ye") - 1;
        expect(growth, `${c.symbol} FY${year}`).toBeGreaterThan(0.05);
      }
    }
  });

  it("loss-makers lose money and are priced on sales", () => {
    for (const c of byArchetype("loss_maker")) {
      expect(n(fy(c, 2026), "net_profit"), c.symbol).toBeLessThan(0);
      expect(ttmEps(c), c.symbol).toBeLessThan(0);
      for (const r of c.annual) expect(n(r, "dividend_per_share")).toBe(0);
    }
  });

  it("negative net worth companies end with equity below zero", () => {
    for (const c of byArchetype("negative_net_worth")) {
      expect(netWorth(fy(c, 2026)), c.symbol).toBeLessThan(0);
      expect(netWorth(fy(c, 2016)), c.symbol).toBeGreaterThan(0);
    }
  });

  it("good banks stay profitable with few bad loans; stressed banks had losses and high GNPA", () => {
    const gnpa = (r: AnnualRow) => (n(r, "gross_npa") / (n(r, "advances") + n(r, "gross_npa") - n(r, "net_npa"))) * 100;
    for (const c of byArchetype("good_bank")) {
      for (const r of c.annual) expect(n(r, "net_profit"), `${c.symbol} FY${r.fiscal_year}`).toBeGreaterThan(0);
      expect(gnpa(fy(c, 2026)), c.symbol).toBeLessThan(3);
    }
    for (const c of byArchetype("stressed_bank")) {
      expect(c.annual.some((r) => n(r, "net_profit") < 0), c.symbol).toBe(true);
      const peak = Math.max(...c.annual.map(gnpa));
      expect(peak, c.symbol).toBeGreaterThan(1.8 * gnpa(fy(c, 2026)));
      expect(c.annual.some((r) => n(r, "equity_issuance") > 0), c.symbol).toBe(true);
    }
  });

  it("the transition company flags FY2021 only", () => {
    const [c] = withTrait("transition");
    for (const r of c.annual) expect(r.flags).toEqual(r.fiscal_year === 2021 ? ["transition"] : []);
    for (const other of DS.companies.filter((x) => x !== c)) for (const r of other.annual) expect(r.flags).toEqual([]);
  });
});

