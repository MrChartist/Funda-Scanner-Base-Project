const DS = generateSampleDataset();
const PLANS = samplePlans();
const PLAN_BY_SYMBOL = new Map<string, SamplePlan>(PLANS.map((p) => [p.symbol, p]));
const TOL = 0.011;

function plan(c: CompanyRecord): SamplePlan {
  const p = PLAN_BY_SYMBOL.get(c.symbol);
  if (!p) throw new Error(`No plan for ${c.symbol}`);
  return p;
}
function family(c: CompanyRecord) {
  return SECTORS[plan(c).entry.sectorKey].family;
}
function byArchetype(a: string): CompanyRecord[] {
  return DS.companies.filter((c) => plan(c).entry.archetype === a);
}
function withTrait(t: string): CompanyRecord[] {
  return DS.companies.filter((c) => (plan(c).entry.traits as readonly string[]).includes(t));
}
/** Reads a field that must be present. */
function n(r: AnnualRow, f: keyof AnnualRow): number {
  const v = r[f] as Num;
  if (v === null || v === undefined) throw new Error(`FY${r.fiscal_year} ${String(f)} is null`);
  return v;
}
function near(a: number, b: number, tol = TOL): boolean {
  return Math.abs(a - b) <= tol;
}
function fy(c: CompanyRecord, year: number): AnnualRow {
  const r = c.annual.find((x) => x.fiscal_year === year);
  if (!r) throw new Error(`${c.symbol} has no FY${year}`);
  return r;
}
function netWorth(r: AnnualRow): number {
  return n(r, "equity_share_capital") + n(r, "other_equity");
}
function centsOf(v: Num): number {
  return Math.round((v ?? 0) * 100);
}

